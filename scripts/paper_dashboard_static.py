#!/usr/bin/env python3
"""paper_dashboard_static.py — self-contained static dashboard for the repo.

Embeds the current paper-journal summary (the same JSON that
paper_dashboard.py serves live at /api/summary) into the dashboard page, so
the result works from GitHub Pages / raw.githubusercontent with no backend.
paper-trading workflow regenerates it after each session and commits it as
paper/dashboard.html.

Run:  python scripts/paper_dashboard_static.py [--out paper/dashboard.html]
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path

from paper_dashboard import PAGE, build_summary

OUT_DEFAULT = Path(__file__).resolve().parent.parent / "paper" / "dashboard.html"

# exact live-only note → static equivalent
NOTE_STATIC = (
    "Source: paper/<strategy>/ (daily.csv · paper_state.json · "
    "trades.csv). Static snapshot regenerated by the "
    "paper-trading workflow."
)


def build_html() -> str:
    summary = build_summary()
    payload = json.dumps(summary, ensure_ascii=False).replace("</", "<\\/")
    html = PAGE.replace(
        '<main id="app">loading…</main>',
        f'<main id="app">loading…</main>\n<script>const DATA = {payload};</script>',
        1,
    )
    # the page normally refetches the API every 15 s; here the data is inline
    html = html.replace(
        'const r=await fetch("/api/summary");',
        "const r=await Promise.resolve(DATA);",
        1,
    )
    html = html.replace(
        "Marks refresh every 15 s from the running session. ",
        NOTE_STATIC,
        1,
    )
    html = html.replace("setInterval(refresh,15000);", "", 1)
    return html


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", type=Path, default=OUT_DEFAULT)
    args = ap.parse_args()
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text(build_html())
    print(f"static dashboard → {args.out}")


if __name__ == "__main__":
    main()
